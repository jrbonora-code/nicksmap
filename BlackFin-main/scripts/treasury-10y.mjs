// Monthly average of the 10-year Treasury par yield, for the estimated balance of a recorded mortgage.
// Usage: node scripts/treasury-10y.mjs [--from 1990]
// Downloads Treasury's daily par yield curve CSV once per year into .local/treasury/ (past years are never fetched
// again; the current year is refreshed), averages the "10 Yr" column by month and writes
// lib/research/treasury-10y-data.ts with the source receipts. Public data; no key.
import fs from 'node:fs/promises';
import path from 'node:path';
import { createHash } from 'node:crypto';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')), '..');
const cache = path.join(root, '.local', 'treasury');
const output = path.join(root, 'lib', 'research', 'treasury-10y-data.ts');
const fromArg = process.argv.indexOf('--from');
const first = fromArg > 0 ? Number(process.argv[fromArg + 1]) : 1990;
const thisYear = new Date().getUTCFullYear();
const url = year => `https://home.treasury.gov/resource-center/data-chart-center/interest-rates/daily-treasury-rates.csv/${year}/all?type=daily_treasury_yield_curve&field_tdr_date_value=${year}&page&_format=csv`;
const sha = buffer => createHash('sha256').update(buffer).digest('hex');
const wait = ms => new Promise(resolve => setTimeout(resolve, ms));

await fs.mkdir(cache, { recursive: true });
const files = [];
const sums = new Map();
for (let year = first; year <= thisYear; year++) {
  const file = path.join(cache, `par-yield-${year}.csv`);
  let raw = null, retrievedAt = null;
  try {
    const stat = await fs.stat(file);
    // A past year is final; the current year is refreshed once a day.
    if (year < thisYear || Date.now() - stat.mtimeMs < 86400000) { raw = await fs.readFile(file); retrievedAt = stat.mtime.toISOString(); }
  } catch { /* not cached yet */ }
  if (!raw) {
    const response = await fetch(url(year), { headers: { 'User-Agent': 'BlackFin research', Accept: 'text/csv' } });
    if (!response.ok) throw new Error(`Treasury ${year}: HTTP ${response.status}`);
    raw = Buffer.from(await response.arrayBuffer());
    retrievedAt = new Date().toISOString();
    await fs.writeFile(file, raw);
    await wait(500);
  }
  const lines = raw.toString('utf8').trim().split(/\r?\n/);
  const header = lines[0].split(',').map(h => h.replace(/"/g, '').trim());
  const at = header.indexOf('10 Yr');
  if (header[0] !== 'Date' || at < 0) throw new Error(`Treasury ${year}: unexpected header ${lines[0].slice(0, 80)}`);
  let days = 0;
  for (const line of lines.slice(1)) {
    const cells = line.split(',');
    const [m, d, y] = cells[0].split('/').map(Number);
    const value = Number(cells[at]);
    if (!y || !m || !d || cells[at] === '' || !Number.isFinite(value)) continue;
    const key = `${y}-${String(m).padStart(2, '0')}`;
    const s = sums.get(key) ?? { total: 0, n: 0 };
    s.total += value; s.n++; sums.set(key, s); days++;
  }
  if (!days) throw new Error(`Treasury ${year}: no 10-year readings`);
  files.push({ year, sha256: sha(raw), bytes: raw.length, days, retrievedAt });
}
const months = Object.fromEntries([...sums.entries()].sort(([a], [b]) => a.localeCompare(b)).map(([k, s]) => [k, Math.round((s.total / s.n) * 1000) / 1000]));
const keys = Object.keys(months);
const body = `// Generated by scripts/treasury-10y.mjs. Do not edit by hand.
// Monthly average of the daily 10-year Treasury par yield (percent), from Treasury's daily par yield curve CSVs.
export const TREASURY_10Y = {
  source: 'U.S. Department of the Treasury, Daily Treasury Par Yield Curve Rates',
  url: 'https://home.treasury.gov/resource-center/data-chart-center/interest-rates/TextView?type=daily_treasury_yield_curve',
  first: ${JSON.stringify(keys[0])}, last: ${JSON.stringify(keys.at(-1))},
  files: ${JSON.stringify(files.map(({ year, sha256, days }) => ({ year, sha256, days })))},
  months: ${JSON.stringify(months)} as Record<string, number>,
};
`;
await fs.writeFile(output, body);
console.log(JSON.stringify({ months: keys.length, first: keys[0], last: keys.at(-1), files: files.length, latest: months[keys.at(-1)] }));
